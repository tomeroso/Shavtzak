const { chromium } = require('playwright');
const BASE='http://127.0.0.1:8787', EXE='/opt/pw-browsers/chromium-1194/chrome-linux/chrome';
const step=(a,b)=>console.log('  '+a+':',b);
(async()=>{const b=await chromium.launch({executablePath:EXE});
const ctx=await b.newContext({viewport:{width:400,height:880},locale:'he-IL',timezoneId:'Asia/Jerusalem'});
const errs=[]; await ctx.addInitScript(()=>{try{localStorage.setItem('sh.sid',JSON.stringify('TESTSID'))}catch(e){}});
const p=await ctx.newPage();
p.on('pageerror',e=>errs.push('PAGEERROR '+e.message));
await p.goto(BASE); await p.waitForSelector('.setup',{timeout:8000});
step('first screen', (await p.$eval('#view',e=>e.innerText)).split('\n').slice(0,4).join(' | '));
step('create button offered', !!(await p.$('#newsh')) ? '✓' : '✗');
await p.click('#newsh'); await p.waitForSelector('#ntitle');
step('import-from-current link', (await p.$('#nfill')) ? 'shown' : 'hidden (no roster yet) ✓');
await p.fill('#ntitle','מוצב חדש');
await p.fill('#npeople',['א א','ב ב','ג ג','ד ד','ה ה','ו ו','ז ז','ח ח','ט ט'].join('\n'));
await p.fill('#nposts','שער\nסיור x2'); await p.fill('#ndays','3');
await p.selectOption('#nfillmode','0');
await p.click('#ngo'); await p.waitForSelector('table.ed',{timeout:8000});
step('empty start', (await p.$$('table.ed .nm')).length === 0 ? 'no assignments ✓' : 'unexpected names');
step('holes flagged', (await p.$$('.add.want')).length > 0 ? '✓' : '✗');
await p.click('#gfill'); await p.waitForTimeout(500);
step('after מלא חורים', (await p.$$('table.ed .nm')).length + ' names on day 1');
await p.click('.tb[data-k="issues"]'); await p.waitForTimeout(200);
step('issues', (await p.$eval('#view',e=>e.innerText)).replace(/\n+/g,' | ').slice(0,150));
console.log(errs.length?'ERRORS:\n'+errs.join('\n'):'  no JS errors ✓');
await b.close();})();
